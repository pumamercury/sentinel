-- Private shared workspace. Only the authenticated Edge API writes these tables.
create table public.sentinel_members (
 id bigint generated by default as identity primary key,
 auth_id uuid unique references auth.users(id) on delete set null,
 email text not null unique,
 role text not null check (role in ('owner','member')),
 disabled boolean not null default false,
 invitation_id uuid,
 invitation_expires timestamptz
);
create table public.sentinel_workspace (
 id boolean primary key default true check (id),
 version bigint not null default 0,
 data jsonb not null check (jsonb_typeof(data) = 'object' and octet_length(data::text) <= 20000000)
);
create table public.sentinel_uploads (
 id uuid primary key,
 auth_id uuid not null references auth.users(id) on delete cascade,
 metadata jsonb not null,
 expires_at timestamptz not null default now() + interval '2 hours'
);
create table public.sentinel_control (key text primary key, data jsonb not null);
alter table public.sentinel_members enable row level security;
alter table public.sentinel_workspace enable row level security;
alter table public.sentinel_uploads enable row level security;
alter table public.sentinel_control enable row level security;
revoke all on public.sentinel_members, public.sentinel_workspace, public.sentinel_uploads, public.sentinel_control from anon, authenticated;
grant all on public.sentinel_members, public.sentinel_workspace, public.sentinel_uploads, public.sentinel_control to service_role;
grant usage, select on sequence public.sentinel_members_id_seq to service_role;
create function public.sentinel_commit(expected_version bigint, next_data jsonb)
returns bigint language sql security invoker set search_path = '' as $$
 update public.sentinel_workspace set data = next_data, version = version + 1
 where id = true and version = expected_version returning version;
$$;
revoke all on function public.sentinel_commit(bigint,jsonb) from public, anon, authenticated;
grant execute on function public.sentinel_commit(bigint,jsonb) to service_role;
insert into storage.buckets(id,name,public,file_size_limit) values ('sentinel-attachments','sentinel-attachments',false,50000000);

create table public.sentinel_companions (
 token_hash text primary key,
 member_id bigint not null references public.sentinel_members(id) on delete cascade,
 expires_at timestamptz not null default now() + interval '90 days'
);
alter table public.sentinel_companions enable row level security;
revoke all on public.sentinel_companions from anon, authenticated;
grant all on public.sentinel_companions to service_role;
create function public.sentinel_reserve_member_ids() returns bigint
language sql security invoker set search_path = '' as $$
 select pg_catalog.setval('public.sentinel_members_id_seq', greatest(coalesce((select max(id) from public.sentinel_members),0)+1,1), false);
$$;
revoke all on function public.sentinel_reserve_member_ids() from public, anon, authenticated;
grant execute on function public.sentinel_reserve_member_ids() to service_role;
